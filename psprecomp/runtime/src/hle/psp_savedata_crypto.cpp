static void memxor(uint8_t* d, const uint8_t* s, size_t n) {
    for (; n > 0; --n) *d++ ^= *s++;
}
static void put_le32(uint8_t* p, uint32_t v) {
    p[0] = uint8_t(v); p[1] = uint8_t(v >> 8); p[2] = uint8_t(v >> 16); p[3] = uint8_t(v >> 24);
}

// The reason for the values from *FromMode calculations are not known.
static int numFromMode(int mode) {
    switch (mode) {
        case 1: return 3;
        case 2: return 5;
        case 3: return 12;
        case 4: return 13;
        case 6: return 17;
        default: return 16;
    }
}
static int numFromMode2(int mode) {
    int num = 18;
    if (mode == 1) num = 4;
    else if (mode == 3) num = 14;
    return num;
}
static int typeFromMode(int mode) {
    return (mode == 1 || mode == 2) ? 83 : ((mode == 3 || mode == 4) ? 87 : 100);
}

// Emulates sceUtilsBufferCopyWithRange for CMD4 (encrypt, out at +20) and
// CMD7 (decrypt, out at +0) on a 20-byte KIRK AES header followed by
// `length` bytes, in place. Only the header fields the commands inspect
// (mode, keyseed, data_size) are modelled.
static int kirkSendCmd(uint8_t* data, int length, int num, bool encrypt) {
    if (length == 0) return -257;                // KIRK_DATA_SIZE_ZERO
    const uint8_t* key = kirk_keyvault(num);
    if (!key) return -257;
    if (encrypt) aes128_cbc_encrypt(key, data + 20, data + 20, size_t(length));
    else         aes128_cbc_decrypt(key, data + 20, data, size_t(length));
    return 0;
}
// CMD5 / CMD8: CMD4 / CMD7 with the per-console key derived from the Fuse
// ID (kirk_individual_key(seed 1) in PPSSPP's kirk_engine.c; the KIRK ROM
// only accepts keyseed 0x100 for them, which is what the callers use).
// The real console's Fuse ID is unknowable, so like PPSSPP we use fixed
// ones; PPSSPP never verifies the hashes that depend on it when loading.
static uint32_t g_fuse90 = 0xBABEF00Du, g_fuse94 = 0xDEADBEEFu;
static bool g_fuse_key_valid = false;
static uint8_t g_fuse_key[16];
static const uint8_t kirk16_key[16] = {0x47, 0x5E, 0x09, 0xF4, 0xA2, 0x37, 0xDA, 0x9B, 0xEF, 0xFF, 0x3B, 0xC0, 0x77, 0x14, 0x3D, 0x8A};

static void derive_fuse_key(uint8_t key_out[16]) {
    uint8_t fuseid[8], subkey_1[16], subkey_2[16], mesh[0x30];
    for (int i = 0; i < 4; ++i) {
        fuseid[7 - i] = uint8_t(g_fuse90 >> (8 * i));
        fuseid[3 - i] = uint8_t(g_fuse94 >> (8 * i));
    }
    for (int i = 0; i < 16; ++i) subkey_2[i] = subkey_1[i] = fuseid[i % 8];
    for (int i = 0; i < 3; ++i) {
        aes128_encrypt_block(kirk16_key, subkey_1, subkey_1);
        aes128_decrypt_block(kirk16_key, subkey_2, subkey_2);
    }
    for (int i = 0; i < 3; ++i) {
        for (int k = 0; k < 3; ++k) aes128_encrypt_block(subkey_1, subkey_2, subkey_2);
        memcpy(&mesh[i * 0x10], subkey_2, 16);
    }
    const int seed = 1;   // CMD5/CMD8 use service seed 1
    memcpy(key_out, (seed & 1) ? &mesh[0x10] : &mesh[0], 16);
    for (int i = 0; i < (seed >> 1) + 1; ++i)
        aes128_encrypt_block(&mesh[0x20], key_out, key_out);
}
void set_fuse_id(uint32_t fuse90, uint32_t fuse94) {
    std::lock_guard<std::mutex> guard(g_lock);
    g_fuse90 = fuse90; g_fuse94 = fuse94; g_fuse_key_valid = false;
}
static int kirkSendFuseCmd(uint8_t* data, int length, bool encrypt) {
    if (length == 0) return -258;
    if (!g_fuse_key_valid) { derive_fuse_key(g_fuse_key); g_fuse_key_valid = true; }
    if (encrypt) aes128_cbc_encrypt(g_fuse_key, data + 20, data + 20, size_t(length));
    else         aes128_cbc_decrypt(g_fuse_key, data + 20, data, size_t(length));
    return 0;
}

static int sub_15B0(uint8_t* data, int alignedLen, uint8_t* buf, int val) {
    uint8_t sp0[16];
    memcpy(sp0, data + alignedLen + 4, 16);
    int res = kirkSendCmd(data, alignedLen, val, false);
    if (res) return res;
    memxor(data, buf, 16);
    memcpy(buf, sp0, 16);
    return 0;
}

static int sub_0000(uint8_t* data_out, uint8_t* data, int alignedLen,
                    const uint8_t* data2, int& data3, int mode) {
    memcpy(data_out + 20, data2, 16);
    int type = typeFromMode(mode);
    int res;
    if (type == 87) memxor(data_out + 20, key19AC, 16);
    else if (type == 100) memxor(data_out + 20, key19DC, 16);

    switch (mode) {  // odd = Cmd, even = FuseCmd
        case 2: case 4: case 6: res = kirkSendFuseCmd(data_out, 16, false); break;
        case 1: case 3: default: res = kirkSendCmd(data_out, 16, numFromMode2(mode), false); break;
    }
    if (type == 87) memxor(data_out, key199C, 16);
    else if (type == 100) memxor(data_out, key19CC, 16);
    if (res) return res;

    uint8_t sp0[16], sp16[16];
    memcpy(sp16, data_out, 16);
    if (data3 == 1) {
        memset(sp0, 0, 16);
    } else {
        memcpy(sp0, sp16, 12);
        put_le32(sp0 + 12, uint32_t(data3 - 1));
    }
    if (alignedLen > 0) {
        for (int i = 20; i < alignedLen + 20; i += 16) {
            memcpy(data_out + i, sp16, 12);
            put_le32(data_out + 12 + i, uint32_t(data3));
            data3++;
        }
    }
    res = sub_15B0(data_out, alignedLen, sp0, type);
    if (res) return res;
    if (alignedLen > 0) memxor(data, data_out, size_t(alignedLen));
    return 0;
}

static int sub_1510(uint8_t* data, int size, uint8_t* result, int num) {
    memxor(data + 20, result, 16);
    int res = kirkSendCmd(data, size, num, true);
    if (res) return res;
    memcpy(result, data + size + 4, 16);
    return 0;
}

int sd_mac_init(MacCtx& ctx, int value) {
    ctx.mode = value;
    memset(ctx.result, 0, 16);
    memset(ctx.key, 0, 16);
    ctx.keyLength = 0;
    return 0;
}

int sd_mac_update(MacCtx& ctx, const uint8_t* data, int length) {
    std::lock_guard<std::mutex> guard(g_lock);
    if (ctx.keyLength >= 17) return -1026;
    if (ctx.keyLength + length < 17) {
        memcpy(ctx.key + ctx.keyLength, data, size_t(length));
        ctx.keyLength = ctx.keyLength + length;
        return 0;
    }
    int num = numFromMode(ctx.mode);
    memset(g_dataBuf2, 0, 2048);
    memcpy(g_dataBuf2, ctx.key, size_t(ctx.keyLength));

    int len = (ctx.keyLength + length) & 0xF;
    if (len == 0) len = 16;
    int newSize = ctx.keyLength;
    ctx.keyLength = len;
    int diff = length - len;
    memcpy(ctx.key, data + diff, size_t(len));
    for (int i = 0; i < diff; i++) {
        if (newSize == 2048) {
            int res = sub_1510(g_dataBuf, 2048, ctx.result, num);
            if (res) return res;
            newSize = 0;
        }
        g_dataBuf2[newSize] = data[i];
        newSize++;
    }
    if (newSize) sub_1510(g_dataBuf, newSize, ctx.result, num);
    return 0;  // original always returns 0 here
}

int sd_mac_final(MacCtx& ctx, uint8_t* in_hash, const uint8_t* in_key) {
    std::lock_guard<std::mutex> guard(g_lock);
    if (ctx.keyLength >= 17) return -1026;
    int num = numFromMode(ctx.mode);
    memset(g_dataBuf2, 0, 16);
    int res = kirkSendCmd(g_dataBuf, 16, num, true);
    if (res) return res;

    uint8_t data1[16], data2[16];
    memcpy(data1, g_dataBuf2, 16);
    int tmp1 = (data1[0] & 0x80) ? 135 : 0;
    for (int i = 0; i < 15; i++) {
        uint8_t val1 = uint8_t(data1[i] << 1);
        uint8_t val2 = data1[i + 1] >> 7;
        data1[i] = val1 | val2;
    }
    uint8_t tmp2 = uint8_t(data1[15] << 1);
    tmp2 = uint8_t(tmp1 ^ tmp2);
    data1[15] = tmp2;

    if (ctx.keyLength < 16) {
        tmp1 = 0;
        if (int8_t(data1[0]) < 0) tmp1 = 135;
        for (int i = 0; i < 15; i++) {
            uint8_t val1 = uint8_t(data1[i] << 1);
            uint8_t val2 = data1[i + 1] >> 7;
            data1[i] = val1 | val2;
        }
        uint8_t t2 = uint8_t(data1[15] << 1);
        t2 = uint8_t(tmp1 ^ t2);
        data1[15] = t2;

        int oldKeyLength = ctx.keyLength;
        ctx.key[ctx.keyLength] = 0x80;
        int i = oldKeyLength + 1;
        if (i < 16) memset(ctx.key + i, 0, size_t(16 - i));
    }
    memxor(ctx.key, data1, 16);
    memcpy(g_dataBuf2, ctx.key, 16);
    memcpy(data2, ctx.result, 16);

    int ret = sub_1510(g_dataBuf, 16, data2, num);
    if (ret) return ret;

    if (ctx.mode == 3 || ctx.mode == 4) memxor(data2, hash198C, 16);
    else if (ctx.mode == 5 || ctx.mode == 6) memxor(data2, hash19BC, 16);

    bool cond = (ctx.mode == 2 || ctx.mode == 4 || ctx.mode == 6);
    if (cond) {
        memcpy(g_dataBuf2, data2, 16);
        int r1 = kirkSendFuseCmd(g_dataBuf, 16, true);
        if (r1) return r1;
        int r2 = kirkSendCmd(g_dataBuf, 16, num, true);
        if (r2) return r2;
        memcpy(data2, g_dataBuf2, 16);
    }
    if (in_key != nullptr) {
        for (int i = 0; i < 16; i++) data2[i] = in_key[i] ^ data2[i];
        memcpy(g_dataBuf2, data2, 16);
        int r3 = kirkSendCmd(g_dataBuf, 16, num, true);
        if (r3) return r3;
        memcpy(data2, g_dataBuf2, 16);
    }
    memcpy(in_hash, data2, 16);
    sd_mac_init(ctx, 0);
    return 0;
}

int sd_cipher_init(CipherCtx& ctx2, int mode, int uknw, uint8_t* data,
                   const uint8_t* cryptkey) {
    std::lock_guard<std::mutex> guard(g_lock);
    ctx2.mode = mode;
    ctx2.unkn = 1;
    if (uknw == 2) {
        memcpy(ctx2.cryptedData, data, 16);
        if (cryptkey) memxor(ctx2.cryptedData, cryptkey, 16);
        return 0;
    } else if (uknw == 1) {
        uint8_t kirkHeader[37];
        uint8_t* kirkData = kirkHeader + 20;
        // sub_17A8: KIRK CMD14 (PRNG) fills the 20-byte header area.
        g_rand(kirkHeader, 20);
        memcpy(kirkHeader + 20, kirkHeader, 16);
        memset(kirkHeader + 32, 0, 4);   // counter part of the IV starts at 0

        int type = typeFromMode(mode);
        if (type == 87) memxor(kirkData, key199C, 16);
        else if (type == 100) memxor(kirkData, key19CC, 16);

        int res;
        switch (mode) {
            case 2: case 4: case 6: res = kirkSendFuseCmd(kirkHeader, 16, true); break;
            case 1: case 3: default: res = kirkSendCmd(kirkHeader, 16, numFromMode2(mode), true); break;
        }
        if (type == 87) memxor(kirkData, key19AC, 16);
        else if (type == 100) memxor(kirkData, key19DC, 16);
        if (res) return res;

        memcpy(ctx2.cryptedData, kirkData, 16);
        memcpy(data, kirkData, 16);
        if (cryptkey) memxor(ctx2.cryptedData, cryptkey, 16);
    }
    return 0;
}

int sd_cipher_update(CipherCtx& ctx, uint8_t* data, int alignedLen) {
    std::lock_guard<std::mutex> guard(g_lock);
    if (alignedLen == 0) return 0;
    if ((alignedLen & 0xF) != 0) return -1025;
    int i = 0;
    uint8_t kirkData[20 + 2048];
    if (uint32_t(alignedLen) >= 2048u) {
        for (i = 0; alignedLen >= 2048; i += 2048) {
            int ctx_unkn = ctx.unkn;
            int res = sub_0000(kirkData, data + i, 2048, ctx.cryptedData, ctx_unkn, ctx.mode);
            ctx.unkn = ctx_unkn;
            alignedLen -= 2048;
            if (res) return res;
        }
    }
    if (alignedLen == 0) return 0;
    int ctx_unkn = ctx.unkn;
    int res = sub_0000(kirkData, data + i, alignedLen, ctx.cryptedData, ctx_unkn, ctx.mode);
    ctx.unkn = ctx_unkn;
    return res;
}

int sd_cipher_final(CipherCtx& ctx) {
    memset(ctx.cryptedData, 0, 16);
    ctx.unkn = 0;
    ctx.mode = 0;
    return 0;
}

// ======================= SavedataParam level =======================
static int align16(int v) { return (v + 15) & ~15; }

int determine_crypt_mode(uint32_t paramCommonSize, uint32_t secureVersion,
                         uint32_t sdk) {
    if (paramCommonSize < 1536) return 1;
    // GetSDKMainVersion(sdk) >= 4  <=>  sdk > 0x0206FFFF
    const bool newHash = sdk > 0x0206FFFFu;
    switch (secureVersion) {
        case 0: return newHash ? 5 : 3;
        case 2: return 3;
        case 3: return newHash ? 5 : 1;
        default: return 1;
    }
}

int crypt_mode_from_params_flag(uint8_t flag) {
    switch (flag) {
        case 0: return 0;
        case 0x01: return 1;
        case 0x21: return 3;
        case 0x41: return 5;
        default: return 1;
    }
}

int encrypt_file(int mode, const uint8_t* plain, size_t n, const uint8_t key[16],
                 std::vector<uint8_t>& file_out, uint8_t hash[16]) {
    const bool hasKey = mode > 1;
    if (hasKey && !key) return -10;
    const uint8_t* ck = hasKey ? key : nullptr;
    int dataLen = int(n), alignedLen = align16(int(n));
    std::vector<uint8_t> buf(size_t(alignedLen) + 16, 0);
    uint8_t* data = buf.data();
    if (n) memcpy(data + 16, plain, n);   // IV room in front (zeroed)
    memset(hash, 0, 16);

    MacCtx c1{};
    CipherCtx c2{};
    if (sd_cipher_init(c2, mode, 1, data, ck) < 0) return -1;
    if (sd_mac_init(c1, mode) < 0) return -2;
    if (sd_mac_update(c1, data, 0x10) < 0) return -3;
    if (sd_cipher_update(c2, data + 0x10, alignedLen) < 0) return -4;
    memset(data + 0x10 + dataLen, 0, size_t(alignedLen - dataLen));
    if (sd_mac_update(c1, data + 0x10, alignedLen) < 0) return -5;
    if (sd_cipher_final(c2) < 0) return -6;
    if (sd_mac_final(c1, hash, ck) < 0) return -7;
    file_out.assign(data, data + dataLen + 16);
    return 0;
}

static int decrypt_one(int mode, uint8_t* data, int dataLen, int alignedLen,
                       const uint8_t* cryptkey, const uint8_t* expectedHash) {
    MacCtx c1{};
    CipherCtx c2{};
    // data points at the 16-byte header; dataLen/alignedLen exclude it.
    if (sd_mac_init(c1, mode) < 0) return -2;
    if (sd_cipher_init(c2, mode, 2, data, cryptkey) < 0) return -3;
    if (sd_mac_update(c1, data, 0x10) < 0) return -4;
    if (sd_mac_update(c1, data + 0x10, alignedLen) < 0) return -5;
    if (sd_cipher_update(c2, data + 0x10, alignedLen) < 0) return -6;
    if (sd_cipher_final(c2) < 0) return -7;
    if (expectedHash) {
        uint8_t hash[16];
        if (sd_mac_final(c1, hash, cryptkey) < 0) return -7;
        if (memcmp(hash, expectedHash, 16) != 0) return -8;
    }
    (void)dataLen;
    return 0;
}

int decrypt_file(int prevMode, int detectedMode, const uint8_t* file, size_t n,
                 const uint8_t key[16], const uint8_t* expectedHash,
                 std::vector<uint8_t>& plain_out, bool* hash_ok) {
    if (hash_ok) *hash_ok = false;
    if (n <= 0x10 || n > 0x40000000u) return -1;
    static const uint8_t zero_key[16] = {0};
    if (!key) key = zero_key;
    const int fileSize = int(n);
    const int alignLen = align16(fileSize);
    std::vector<uint8_t> work(size_t(alignLen), 0);

    auto reset = [&]() {
        std::fill(work.begin(), work.end(), 0);
        memcpy(work.data(), file, n);
    };
    auto attempt = [&](int mode, const uint8_t* eh) {
        return decrypt_one(mode, work.data(), fileSize - 0x10, alignLen - 0x10,
                           mode > 1 ? key : nullptr, eh);
    };

    // Mirrors SavedataParam::LoadCryptedSave: the mode recorded in
    // PARAM.SFO wins over the detected one; fall back to the detected
    // one; finally retry ignoring a mismatching hash ("likely corrupt"
    // but PPSSPP loads it anyway).
    int decryptMode = (prevMode != 0 && prevMode != detectedMode) ? prevMode
                                                                  : detectedMode;
    reset();
    int err = attempt(decryptMode, expectedHash);
    if (err != 0 && detectedMode != decryptMode) {
        reset();
        err = attempt(detectedMode, expectedHash);
        if (err == 0 && hash_ok) *hash_ok = expectedHash != nullptr;
    } else if (err == 0 && hash_ok) {
        *hash_ok = expectedHash != nullptr;
    }
    if (err != 0 && expectedHash) {
        reset();
        err = attempt(decryptMode, nullptr);
    }
    if (err != 0) return err;
    plain_out.assign(work.begin() + 0x10, work.begin() + fileSize);
    return 0;
}

int build_hash(uint8_t out[16], const uint8_t* data, unsigned len,
               int mode, const uint8_t* cryptkey) {
    MacCtx c1{};
    memset(out, 0, 16);
    if (sd_mac_init(c1, mode & 0xFF) < 0) return -1;
    if (sd_mac_update(c1, data, int(len)) < 0) return -2;
    if (sd_mac_final(c1, out, cryptkey) < 0) {
        // Same as PPSSPP: fuse-keyed modes are unavailable, so the
        // "hash" is 0x01 bytes and the call still reports success.
        memset(out, 0x01, 16);
        return 0;
    }
    return 0;
}

int update_sfo_hash(std::vector<uint8_t>& sfo, size_t off, int encryptmode) {
    if (sfo.size() % 16 != 0 || off + 128 > sfo.size()) return -1;
    uint8_t* d = sfo.data();
    const unsigned alignedLen = unsigned(sfo.size());
    memset(d + off, 0, 128);
    uint8_t filehash[16];
    int ret;

    int firstHashMode = (encryptmode & 2) ? 4 : 2;
    int secondHashMode = (encryptmode & 2) ? 3 : 0;
    if (encryptmode & 4) { firstHashMode = 6; secondHashMode = 5; }

    if ((ret = build_hash(filehash, d, alignedLen, firstHashMode, nullptr)) < 0)
        return ret - 400;
    memcpy(d + off + 0x20, filehash, 0x10);
    d[off] |= 0x01;

    if (encryptmode & 6) {
        d[off] |= uint8_t((encryptmode & 6) << 4);
        if ((ret = build_hash(filehash, d, alignedLen, secondHashMode, nullptr)) < 0)
            return ret - 500;
        memcpy(d + off + 0x70, filehash, 0x10);
    }
    if ((ret = build_hash(filehash, d, alignedLen, 1, nullptr)) < 0)
        return ret - 600;
    memcpy(d + off + 0x10, filehash, 0x10);
    return 0;
}

