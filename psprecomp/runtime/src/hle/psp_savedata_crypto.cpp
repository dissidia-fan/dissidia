namespace {
struct AesTables {
    uint8_t sbox[256], inv[256];
    AesTables() {
        // Generate the S-box from the GF(2^8) inverse + affine transform.
        uint8_t p = 1, q = 1;
        do {
            p = p ^ uint8_t(p << 1) ^ ((p & 0x80) ? 0x1B : 0);
            q ^= q << 1; q ^= q << 2; q ^= q << 4;
            if (q & 0x80) q ^= 0x09;
            uint8_t x = q ^ uint8_t((q << 1) | (q >> 7)) ^
                        uint8_t((q << 2) | (q >> 6)) ^
                        uint8_t((q << 3) | (q >> 5)) ^
                        uint8_t((q << 4) | (q >> 4));
            sbox[p] = x ^ 0x63;
        } while (p != 1);
        sbox[0] = 0x63;
        for (int i = 0; i < 256; ++i) inv[sbox[i]] = uint8_t(i);
    }
};
const AesTables& tbl() { static const AesTables t; return t; }

inline uint8_t xt(uint8_t x) { return uint8_t((x << 1) ^ ((x & 0x80) ? 0x1B : 0)); }
inline uint8_t mul(uint8_t a, uint8_t b) {
    uint8_t r = 0;
    while (b) { if (b & 1) r ^= a; a = xt(a); b >>= 1; }
    return r;
}

struct RoundKeys { uint8_t rk[11][16]; };
void expand(const uint8_t key[16], RoundKeys& k) {
    const auto& t = tbl();
    uint8_t rc = 1;
    memcpy(k.rk[0], key, 16);
    for (int r = 1; r <= 10; ++r) {
        const uint8_t* p = k.rk[r - 1];
        uint8_t* n = k.rk[r];
        n[0] = p[0] ^ t.sbox[p[13]] ^ rc;
        n[1] = p[1] ^ t.sbox[p[14]];
        n[2] = p[2] ^ t.sbox[p[15]];
        n[3] = p[3] ^ t.sbox[p[12]];
        for (int i = 4; i < 16; ++i) n[i] = p[i] ^ n[i - 4];
        rc = xt(rc);
    }
}
void enc_block(const RoundKeys& k, const uint8_t in[16], uint8_t out[16]) {
    const auto& t = tbl();
    uint8_t s[16];
    for (int i = 0; i < 16; ++i) s[i] = in[i] ^ k.rk[0][i];
    for (int r = 1; r <= 10; ++r) {
        uint8_t b[16];
        for (int i = 0; i < 16; ++i) b[i] = t.sbox[s[i]];
        // ShiftRows (column-major state)
        uint8_t u[16];
        for (int c = 0; c < 4; ++c)
            for (int row = 0; row < 4; ++row)
                u[c * 4 + row] = b[((c + row) & 3) * 4 + row];
        if (r != 10) {
            for (int c = 0; c < 4; ++c) {
                uint8_t* a = u + c * 4;
                uint8_t a0 = a[0], a1 = a[1], a2 = a[2], a3 = a[3];
                a[0] = xt(a0) ^ (xt(a1) ^ a1) ^ a2 ^ a3;
                a[1] = a0 ^ xt(a1) ^ (xt(a2) ^ a2) ^ a3;
                a[2] = a0 ^ a1 ^ xt(a2) ^ (xt(a3) ^ a3);
                a[3] = (xt(a0) ^ a0) ^ a1 ^ a2 ^ xt(a3);
            }
        }
        for (int i = 0; i < 16; ++i) s[i] = u[i] ^ k.rk[r][i];
    }
    memcpy(out, s, 16);
}
void dec_block(const RoundKeys& k, const uint8_t in[16], uint8_t out[16]) {
    const auto& t = tbl();
    uint8_t s[16];
    for (int i = 0; i < 16; ++i) s[i] = in[i] ^ k.rk[10][i];
    for (int r = 9; r >= 0; --r) {
        // InvShiftRows
        uint8_t u[16];
        for (int c = 0; c < 4; ++c)
            for (int row = 0; row < 4; ++row)
                u[((c + row) & 3) * 4 + row] = s[c * 4 + row];
        for (int i = 0; i < 16; ++i) u[i] = t.inv[u[i]] ^ k.rk[r][i];
        if (r != 0) {
            for (int c = 0; c < 4; ++c) {
                uint8_t* a = u + c * 4;
                uint8_t a0 = a[0], a1 = a[1], a2 = a[2], a3 = a[3];
                a[0] = mul(a0, 14) ^ mul(a1, 11) ^ mul(a2, 13) ^ mul(a3, 9);
                a[1] = mul(a0, 9) ^ mul(a1, 14) ^ mul(a2, 11) ^ mul(a3, 13);
                a[2] = mul(a0, 13) ^ mul(a1, 9) ^ mul(a2, 14) ^ mul(a3, 11);
                a[3] = mul(a0, 11) ^ mul(a1, 13) ^ mul(a2, 9) ^ mul(a3, 14);
            }
        }
        memcpy(s, u, 16);
    }
    memcpy(out, s, 16);
}
}  // namespace

void aes128_encrypt_block(const uint8_t key[16], const uint8_t in[16], uint8_t out[16]) {
    RoundKeys k; expand(key, k); enc_block(k, in, out);
}
void aes128_decrypt_block(const uint8_t key[16], const uint8_t in[16], uint8_t out[16]) {
    RoundKeys k; expand(key, k); dec_block(k, in, out);
}
void aes128_cbc_encrypt(const uint8_t key[16], const uint8_t* in, uint8_t* out, size_t len) {
    RoundKeys k; expand(key, k);
    uint8_t prev[16] = {0};
    for (size_t i = 0; i + 16 <= len; i += 16) {
        uint8_t b[16];
        for (int j = 0; j < 16; ++j) b[j] = in[i + j] ^ prev[j];
        enc_block(k, b, prev);
        memcpy(out + i, prev, 16);
    }
}
void aes128_cbc_decrypt(const uint8_t key[16], const uint8_t* in, uint8_t* out, size_t len) {
    RoundKeys k; expand(key, k);
    uint8_t prev[16] = {0};
    for (size_t i = 0; i + 16 <= len; i += 16) {
        uint8_t cur[16], b[16];
        memcpy(cur, in + i, 16);  // copy first: in/out may overlap
        dec_block(k, cur, b);
        for (int j = 0; j < 16; ++j) out[i + j] = b[j] ^ prev[j];
        memcpy(prev, cur, 16);
    }
}

const uint8_t* kirk_keyvault(int seed) {
    return (seed < 0 || seed >= 0x80) ? nullptr : g_keyvault[seed];
}

