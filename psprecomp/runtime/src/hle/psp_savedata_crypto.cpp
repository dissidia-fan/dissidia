static void default_random(uint8_t* out, size_t len) {
    FILE* f = fopen("/dev/urandom", "rb");
    size_t got = f ? fread(out, 1, len, f) : 0;
    if (f) fclose(f);
    // Fallback (never expected on Linux/macOS): LCG seeded from addresses.
    static uint64_t s = 0x9E3779B97F4A7C15ull ^ reinterpret_cast<uintptr_t>(&s);
    for (size_t i = got; i < len; ++i) { s = s * 6364136223846793005ull + 1442695040888963407ull; out[i] = uint8_t(s >> 56); }
}
static RandomFn g_rand = default_random;
void set_random_source(RandomFn fn) { g_rand = fn ? fn : default_random; }

